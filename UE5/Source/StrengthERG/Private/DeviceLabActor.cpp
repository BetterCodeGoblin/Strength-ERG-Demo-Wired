// DeviceLabActor.cpp
// Owns three ErgManagerComponents and exposes unified debug telemetry.
// One component per channel; each connects to its own bridge process/port.

#include "DeviceLabActor.h"
#include "Engine/Engine.h"

// ?????????????????????????????????????????????????????????????????????????????
//  Constructor — create sub-components, set channel labels and default ports
// ?????????????????????????????????????????????????????????????????????????????

ADeviceLabActor::ADeviceLabActor()
{
    PrimaryActorTick.bCanEverTick = true;

    // ?? Strength — PM5BleBridge serves port 6789, launched from here ????????
    StrengthDevice = CreateDefaultSubobject<UErgManagerComponent>(TEXT("StrengthDevice"));
    StrengthDevice->DeviceChannel  = EDeviceChannel::Strength;
    StrengthDevice->BridgePort     = 6789;
    StrengthDevice->bUseJsonFormat = true;
    // PM5BleBridge.exe manages all three BLE connections and all three ports.
    // We launch it once from the Strength slot; Rowing and Cycling slots connect
    // to their ports without launching a separate process.
    StrengthDevice->BridgeExePath  = TEXT("../PM5BleBridge/bin/Release/net8.0-windows/PM5BleBridge.exe");

    // ?? Rowing — PM5BleBridge serves port 6791, no separate launch ??????????
    RowingDevice = CreateDefaultSubobject<UErgManagerComponent>(TEXT("RowingDevice"));
    RowingDevice->DeviceChannel  = EDeviceChannel::Rowing;
    RowingDevice->BridgePort     = 6791;
    RowingDevice->bUseJsonFormat = true;
    RowingDevice->BridgeExePath  = TEXT("");   // empty = no auto-launch

    // ?? Cycling — PM5BleBridge serves port 6792, no separate launch ?????????
    CyclingDevice = CreateDefaultSubobject<UErgManagerComponent>(TEXT("CyclingDevice"));
    CyclingDevice->DeviceChannel  = EDeviceChannel::Cycling;
    CyclingDevice->BridgePort     = 6792;
    CyclingDevice->bUseJsonFormat = true;
    CyclingDevice->BridgeExePath  = TEXT("");   // empty = no auto-launch
}

// ?????????????????????????????????????????????????????????????????????????????
//  BeginPlay — wire per-channel delegates to the aggregate forwarder
// ?????????????????????????????????????????????????????????????????????????????

void ADeviceLabActor::BeginPlay()
{
    Super::BeginPlay();

    StrengthDevice->OnErgDataUpdated.AddDynamic(this, &ADeviceLabActor::OnStrengthUpdated);
    RowingDevice  ->OnErgDataUpdated.AddDynamic(this, &ADeviceLabActor::OnRowingUpdated);
    CyclingDevice ->OnErgDataUpdated.AddDynamic(this, &ADeviceLabActor::OnCyclingUpdated);

    UE_LOG(LogTemp, Log, TEXT("[DeviceLab] Three device channels initialised."));
    UE_LOG(LogTemp, Log, TEXT("[DeviceLab]   Strength -> port %d"), StrengthDevice->BridgePort);
    UE_LOG(LogTemp, Log, TEXT("[DeviceLab]   Rowing   -> port %d"), RowingDevice->BridgePort);
    UE_LOG(LogTemp, Log, TEXT("[DeviceLab]   Cycling  -> port %d"), CyclingDevice->BridgePort);
}

// ?????????????????????????????????????????????????????????????????????????????
//  Tick — print debug lines to viewport every frame (GEngine on-screen display)
// ?????????????????????????????????????????????????????????????????????????????

void ADeviceLabActor::Tick(float DeltaSeconds)
{
    Super::Tick(DeltaSeconds);

#if !UE_BUILD_SHIPPING
    if (GEngine)
    {
        // Keys 10/11/12 — stable keys so lines don't stack up each frame
        GEngine->AddOnScreenDebugMessage(10, 0.f, FColor::Cyan,    StrengthDevice->GetDebugLine());
        GEngine->AddOnScreenDebugMessage(11, 0.f, FColor::Green,   RowingDevice  ->GetDebugLine());
        GEngine->AddOnScreenDebugMessage(12, 0.f, FColor::Yellow,  CyclingDevice ->GetDebugLine());
    }
#endif
}

// ?????????????????????????????????????????????????????????????????????????????
//  Accessors
// ?????????????????????????????????????????????????????????????????????????????

FErgData ADeviceLabActor::GetStrengthData() const { return StrengthDevice->GetCurrentData(); }
FErgData ADeviceLabActor::GetRowingData()   const { return RowingDevice  ->GetCurrentData(); }
FErgData ADeviceLabActor::GetCyclingData()  const { return CyclingDevice ->GetCurrentData(); }

FString ADeviceLabActor::GetAllDebugText() const
{
    return FString::Printf(TEXT("%s\n%s\n%s"),
        *StrengthDevice->GetDebugLine(),
        *RowingDevice  ->GetDebugLine(),
        *CyclingDevice ->GetDebugLine());
}

// ?????????????????????????????????????????????????????????????????????????????
//  Aggregate delegate forwarders
// ?????????????????????????????????????????????????????????????????????????????

void ADeviceLabActor::OnStrengthUpdated(FErgData Data)
{
    OnAnyDeviceUpdated.Broadcast(EDeviceChannel::Strength, Data);
}

void ADeviceLabActor::OnRowingUpdated(FErgData Data)
{
    OnAnyDeviceUpdated.Broadcast(EDeviceChannel::Rowing, Data);
}

void ADeviceLabActor::OnCyclingUpdated(FErgData Data)
{
    OnAnyDeviceUpdated.Broadcast(EDeviceChannel::Cycling, Data);
}
